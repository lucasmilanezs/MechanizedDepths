// TUNGSTEN NORMALIZER
// Wolframite is the primitive; every tungsten form becomes molten tungsten only in the
// Industrial Crucible, and molten tungsten becomes items only by casting.

ServerEvents.recipes(event => {
  const MOLTEN = 'createmetallurgy:molten_tungsten';
  const SLAG = 'createmetallurgy:molten_slag';

  [
    'createmetallurgy:melting/tungsten/coin',
    'createmetallurgy:melting/tungsten/dirty_dust',
    'createmetallurgy:melting/tungsten/dust',
    'createmetallurgy:melting/tungsten/gear',
    'createmetallurgy:melting/tungsten/ingot',
    'createmetallurgy:melting/tungsten/nugget',
    'createmetallurgy:melting/tungsten/plate',
    'createmetallurgy:melting/tungsten/raw_material',
    'createmetallurgy:melting/tungsten/rod',
    'createmetallurgy:melting/tungsten/wire',
    'createmetalwork:create/compat/createmetallurgy/melting/dusts/dirty/molten_tungsten_from_melting_dirty_dust_heated',
    'createmetalwork:create/compat/createmetallurgy/melting/dusts/molten_tungsten_from_melting_dust_heated',
    'createmetalwork:create/compat/createmetallurgy/molten_metals/mixing/molten_tungsten_from_mixing_heated_createmetallurgy',
    'createmetalwork:create/compat/mixing/ingot_melting/molten_tungsten_from_melting',
    'createmetalwork:create/compat/mixing/molten_tungsten_from_mixing_heated',
    'createmetalwork:create/compat/mixing/molten_tungsten_from_mixing_heated_northstar',
    'createmetalwork:create/compat/molten_metals/mixing/molten_tungsten_from_mixing_heated',
    'createmetalwork:create/compat/compacting/tungsten_ingot_from_compacting_heated',
    'createmetalwork:create/compat/compacting/tungsten_ingot_from_compacting_heated_northstar',
    'createmetalwork:create/compat/compacting/tungsten_ingot_from_compacting_molten_indrev',
    'createmetalwork:create/compat/compacting/tungsten_ingot_from_compacting_molten_northstar',
    'createmetalwork:create/compat/createmetallurgy/tfmg/industrial_blasting/molten_tungsten_from_industrial_blasting_createmetallurgy',
    'createmetalwork:create/compat/tfmg/industrial_blasting/molten_tungsten_from_industrial_blasting',
    'immersiveengineering:arcfurnace/dust_tungsten',
    'immersiveengineering:arcfurnace/ore_tungsten',
    'immersiveengineering:arcfurnace/raw_block_tungsten',
    'immersiveengineering:arcfurnace/raw_ore_tungsten',
    'tconstruct:smeltery/melting/metal/tungsten/block',
    'tconstruct:smeltery/melting/metal/tungsten/dust',
    'tconstruct:smeltery/melting/metal/tungsten/ingot',
    'tconstruct:smeltery/melting/metal/tungsten/nugget',
    'tconstruct:smeltery/melting/metal/tungsten/ore_dense',
    'tconstruct:smeltery/melting/metal/tungsten/ore_singular',
    'tconstruct:smeltery/melting/metal/tungsten/ore_sparse',
    'tconstruct:smeltery/melting/metal/tungsten/raw',
    'tconstruct:smeltery/melting/metal/tungsten/raw_block'
  ].forEach(id => event.remove({ id: id }));

  // [ingredient, name, molten mB, slag mB, ticks]; the block keeps Metallurgy's own recipe.
  const PORTS = [
    [{ tag: 'forge:ores/tungsten' }, 'ore', 90, 45, 200],
    [{ tag: 'forge:raw_materials/tungsten' }, 'raw_material', 90, 45, 200],
    [{ tag: 'forge:storage_blocks/raw_tungsten' }, 'raw_block', 810, 405, 224],
    [{ item: 'createmetallurgy:crushed_raw_tungsten' }, 'crushed_raw', 90, 0, 200],
    [{ tag: 'forge:dirty_dusts/tungsten' }, 'dirty_dust', 90, 30, 200],
    [{ tag: 'forge:dusts/dirty/tungsten' }, 'dirty_dust_metalwork', 90, 30, 200],
    [{ tag: 'forge:dusts/tungsten' }, 'dust', 90, 0, 200],
    [{ tag: 'forge:ingots/tungsten' }, 'ingot', 90, 0, 100],
    [{ tag: 'forge:nuggets/tungsten' }, 'nugget', 10, 0, 20],
    [{ tag: 'forge:plates/tungsten' }, 'plate', 90, 0, 100],
    [{ tag: 'forge:rods/tungsten' }, 'rod', 45, 0, 60],
    [{ tag: 'forge:wires/tungsten' }, 'wire', 45, 0, 60],
    [{ tag: 'forge:gears/tungsten' }, 'gear', 360, 0, 200],
    [{ tag: 'forge:coins/tungsten' }, 'coin', 10, 0, 20]
  ];

  PORTS.forEach(port => {
    let results = [{ fluid: MOLTEN, amount: port[2] }];
    if (port[3] > 0) results.push({ fluid: SLAG, amount: port[3] });
    let recipe = {
      type: 'createmetallurgy:bulk_melting',
      ingredients: [port[0]],
      minHeatRequirement: 9,
      maxHeatRequirement: 50,
      processingTime: port[4],
      results: results
    };
    if (port[0].tag) {
      recipe.conditions = [{ type: 'forge:not', value: { type: 'forge:tag_empty', tag: port[0].tag } }];
    }
    event.custom(recipe).id(`kubejs:tungsten_normalizer/bulk_melting/${port[1]}`);
  });
});

// Arc Furnace recycling is generated by IE at load time; ignored components keep tungsten out of it.
ServerEvents.tags('item', event => {
  [
    'forge:ingots/tungsten',
    'forge:nuggets/tungsten',
    'forge:plates/tungsten',
    'forge:rods/tungsten',
    'forge:wires/tungsten',
    'forge:gears/tungsten',
    'forge:storage_blocks/tungsten'
  ].forEach(tag => event.add('immersiveengineering:recycling/ignored_components', `#${tag}`));
});
